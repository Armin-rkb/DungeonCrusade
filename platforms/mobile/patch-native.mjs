#!/usr/bin/env node
// Patches the Capacitor-generated native projects for Dungeon Crusade.
// Idempotent: running it again produces byte-identical files.
//
//   node platforms/mobile/patch-native.mjs android   # AndroidManifest.xml + app/build.gradle
//   node platforms/mobile/patch-native.mjs ios       # Info.plist + project.pbxproj (version)
//   node platforms/mobile/patch-native.mjs --self-test
//
// Android: landscape (sensorLandscape), controller-friendly configChanges,
//   deep links dungeoncrusade://join/CODE + https://<public host>/?join=CODE
//   (App Links), game category, optional gamepad feature.
// iOS: landscape only, UIRequiresFullScreen, URL scheme dungeoncrusade,
//   extended game controller support (MFi / Xbox / PlayStation) so the
//   Gamepad API works in WKWebView, game category (Game Mode).
//
// Both: app version = DC_VERSION (release tag) or the root package.json
// "version"; build number (Android versionCode / iOS CURRENT_PROJECT_VERSION)
// = DC_BUILD_NUMBER, else GITHUB_RUN_NUMBER, else left unchanged. Store
// uploads need it to grow.
//
// The https host comes from DC_PUBLIC_HOST, else the host of VITE_PUBLIC_URL,
// else dungeon-crusade.fly.dev.
//
// Plain string/regex editing on purpose (no XML/plist dependencies); both
// files are machine-generated by `npx cap add` with a stable layout.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const SCHEME = 'dungeoncrusade';
export const DEFAULT_HOST = 'dungeon-crusade.fly.dev';
const MARK_BEGIN = '<!-- dungeon-crusade:deep-links begin -->';
const MARK_END = '<!-- dungeon-crusade:deep-links end -->';
const CONFIG_CHANGES = [
  'orientation', 'keyboardHidden', 'keyboard', 'screenSize', 'locale', 'smallestScreenSize',
  'screenLayout', 'uiMode', 'navigation', 'density',
];

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

export function publicHost(env = process.env) {
  if (env.DC_PUBLIC_HOST) return env.DC_PUBLIC_HOST.trim();
  if (env.VITE_PUBLIC_URL) {
    try {
      return new URL(env.VITE_PUBLIC_URL).hostname;
    } catch {
      /* fall through */
    }
  }
  return DEFAULT_HOST;
}

// ------------------------------------------------------------------ Android

/** Matches one XML start tag, honouring quoted attribute values. */
const startTag = (name) => new RegExp(`<${name}\\b(?:[^>"']|"[^"]*"|'[^']*')*>`, 'g');

/**
 * Sets (or replaces) one attribute inside a start tag string.
 * @param {string} tag  e.g. '<activity android:name=".MainActivity" ...>'
 */
export function setAttr(tag, name, value) {
  const re = new RegExp(`(\\s)${name.replace(/[.:]/g, '\\$&')}="[^"]*"`);
  if (re.test(tag)) return tag.replace(re, `$1${name}="${value}"`);
  // Insert before the closing ">" (or "/>"), on its own line like Capacitor's template.
  const indent = /\n(\s+)\S/.exec(tag)?.[1] ?? ' ';
  return tag.replace(/\s*(\/?>)$/, `\n${indent}${name}="${value}"$1`);
}

function getAttr(tag, name) {
  return new RegExp(`\\s${name.replace(/[.:]/g, '\\$&')}="([^"]*)"`).exec(tag)?.[1] ?? null;
}

export function patchAndroidManifest(xml, { host = DEFAULT_HOST } = {}) {
  let out = xml;

  // <application>: mark the app as a game (Play Store category, Game Dashboard).
  out = out.replace(startTag('application'), (tag) => setAttr(tag, 'android:appCategory', 'game'));

  // MainActivity: landscape + config changes that must not restart the
  // activity (controllers connecting count as keyboard/navigation changes).
  const activities = [...out.matchAll(startTag('activity'))];
  const main = activities.find((m) => /android:name="[^"]*MainActivity"/.test(m[0]));
  if (!main) throw new Error('AndroidManifest.xml: MainActivity not found');
  let tag = main[0];
  tag = setAttr(tag, 'android:screenOrientation', 'sensorLandscape');
  const existing = (getAttr(tag, 'android:configChanges') ?? '').split('|').filter(Boolean);
  const merged = [...existing, ...CONFIG_CHANGES.filter((c) => !existing.includes(c))];
  tag = setAttr(tag, 'android:configChanges', merged.join('|'));
  out = out.slice(0, main.index) + tag + out.slice(main.index + main[0].length);

  // Deep links, inside MainActivity (replace a previous block so host changes apply).
  const activityStart = out.indexOf(tag);
  const activityEnd = out.indexOf('</activity>', activityStart);
  if (activityEnd < 0) throw new Error('AndroidManifest.xml: </activity> not found');
  let body = out.slice(activityStart + tag.length, activityEnd);
  body = body.replace(new RegExp(`\\n?[ \\t]*${escapeRe(MARK_BEGIN)}[\\s\\S]*?${escapeRe(MARK_END)}`), '');
  const ind = /\n([ \t]+)<intent-filter/.exec(body)?.[1] ?? '            ';
  const filters = [
    MARK_BEGIN,
    `<!-- ${SCHEME}://join/CODE (custom scheme, works without verification) -->`,
    '<intent-filter>',
    '    <action android:name="android.intent.action.VIEW" />',
    '    <category android:name="android.intent.category.DEFAULT" />',
    '    <category android:name="android.intent.category.BROWSABLE" />',
    `    <data android:scheme="${SCHEME}" android:host="join" />`,
    '</intent-filter>',
    `<!-- https://${host}/?join=CODE (App Link; needs /.well-known/assetlinks.json on the host) -->`,
    '<intent-filter android:autoVerify="true">',
    '    <action android:name="android.intent.action.VIEW" />',
    '    <category android:name="android.intent.category.DEFAULT" />',
    '    <category android:name="android.intent.category.BROWSABLE" />',
    `    <data android:scheme="https" android:host="${host}" />`,
    '</intent-filter>',
    MARK_END,
  ].map((l) => ind + l);
  body = body.replace(/\s*$/, '') + '\n\n' + filters.join('\n') + '\n\n' + ind.slice(4);
  out = out.slice(0, activityStart + tag.length) + body + out.slice(activityEnd);

  // Controllers are supported but not required (touch controls exist).
  const feature = '<uses-feature android:name="android.hardware.gamepad" android:required="false" />';
  if (!out.includes('android.hardware.gamepad')) {
    out = out.replace(/(\n?)([ \t]*)<\/manifest>/, `$1    ${feature}\n$2</manifest>`);
  }
  return out;
}

// ---------------------------------------------------------------------- iOS

/**
 * Minimal plist reader: returns the root <dict> span and its direct
 * key/value entries with their character ranges.
 */
function plistEntries(xml) {
  const rootOpen = /<plist\b[^>]*>\s*<dict>/.exec(xml);
  if (!rootOpen) throw new Error('Info.plist: root <dict> not found');
  let i = rootOpen.index + rootOpen[0].length;
  const entries = [];
  const tagRe = /<(\/?)(\w+)([^>]*?)(\/?)>|<!--[\s\S]*?-->/g;
  /** Returns the end index of the element starting at `from`. */
  const elementEnd = (from) => {
    tagRe.lastIndex = from;
    let depth = 0;
    for (let m; (m = tagRe.exec(xml)); ) {
      if (m[0].startsWith('<!--')) continue;
      const [, closing, , , selfClosing] = m;
      if (selfClosing) {
        if (depth === 0) return tagRe.lastIndex;
      } else if (closing) {
        depth--;
        if (depth === 0) return tagRe.lastIndex;
      } else depth++;
    }
    throw new Error('Info.plist: unbalanced element');
  };
  for (;;) {
    const ws = /^(?:\s|<!--[\s\S]*?-->)*/.exec(xml.slice(i))[0];
    i += ws.length;
    if (xml.startsWith('</dict>', i)) return { entries, rootClose: i };
    const key = /^<key>([^<]*)<\/key>/.exec(xml.slice(i));
    if (!key) throw new Error(`Info.plist: expected <key> at ${i}`);
    const keyStart = i;
    i += key[0].length;
    i += /^\s*/.exec(xml.slice(i))[0].length;
    const valueStart = i;
    const valueEnd = elementEnd(i);
    entries.push({ key: key[1], keyStart, valueStart, valueEnd });
    i = valueEnd;
  }
}

/** Sets a top-level key to a plist XML value (replacing any existing value). */
export function setPlistKey(xml, key, valueXml) {
  const { entries, rootClose } = plistEntries(xml);
  const hit = entries.find((e) => e.key === key);
  if (hit) return xml.slice(0, hit.valueStart) + valueXml + xml.slice(hit.valueEnd);
  const before = xml.slice(0, rootClose).replace(/\s*$/, '');
  return `${before}\n\t<key>${key}</key>\n\t${valueXml}\n${xml.slice(rootClose)}`;
}

export function getPlistValue(xml, key) {
  const hit = plistEntries(xml).entries.find((e) => e.key === key);
  return hit ? xml.slice(hit.valueStart, hit.valueEnd) : null;
}

const plistArray = (items, indent = '\t') =>
  `<array>\n${items.map((s) => `${indent}\t${s}`).join('\n')}\n${indent}</array>`;

export function patchInfoPlist(xml) {
  let out = xml;
  const landscape = plistArray([
    '<string>UIInterfaceOrientationLandscapeRight</string>',
    '<string>UIInterfaceOrientationLandscapeLeft</string>',
  ]);
  out = setPlistKey(out, 'UISupportedInterfaceOrientations', landscape);
  out = setPlistKey(out, 'UISupportedInterfaceOrientations~ipad', landscape);
  // Required on iPad to restrict orientations (opts out of Split View).
  out = setPlistKey(out, 'UIRequiresFullScreen', '<true/>');
  out = setPlistKey(out, 'UIStatusBarHidden', '<true/>');

  // dungeoncrusade://join/CODE -> App plugin "appUrlOpen". Keep other schemes.
  const ourType = [
    '<dict>',
    '\t\t\t<key>CFBundleURLName</key>',
    '\t\t\t<string>com.dungeoncrusade.game</string>',
    '\t\t\t<key>CFBundleURLSchemes</key>',
    '\t\t\t<array>',
    `\t\t\t\t<string>${SCHEME}</string>`,
    '\t\t\t</array>',
    '\t\t</dict>',
  ].join('\n');
  const urlTypes = getPlistValue(out, 'CFBundleURLTypes');
  if (!urlTypes || /^<array\s*\/>$/.test(urlTypes)) {
    out = setPlistKey(out, 'CFBundleURLTypes', `<array>\n\t\t${ourType}\n\t</array>`);
  } else if (!urlTypes.includes(`<string>${SCHEME}</string>`)) {
    out = setPlistKey(out, 'CFBundleURLTypes', urlTypes.replace(/\s*<\/array>$/, `\n\t\t${ourType}\n\t</array>`));
  }

  // Game controllers: lets WKWebView's Gamepad API see MFi / Xbox / DualShock /
  // DualSense pads and lets controllers drive the app.
  out = setPlistKey(out, 'GCSupportsControllerUserInteraction', '<true/>');
  out = setPlistKey(
    out,
    'GCSupportedGameControllers',
    plistArray(['<dict>\n\t\t\t<key>ProfileName</key>\n\t\t\t<string>ExtendedGamepad</string>\n\t\t</dict>']),
  );
  // Game category: enables Game Mode (iOS 18+) and lowers controller latency.
  out = setPlistKey(out, 'LSApplicationCategoryType', '<string>public.app-category.action-games</string>');
  out = setPlistKey(out, 'GCSupportsGameMode', '<true/>');
  // No custom crypto (TLS only): skips the export-compliance question on upload.
  out = setPlistKey(out, 'ITSAppUsesNonExemptEncryption', '<false/>');
  return out;
}

// ------------------------------------------------------------------ version

/** android/app/build.gradle: versionName / versionCode. */
export function patchGradleVersion(gradle, { versionName, versionCode }) {
  let out = gradle.replace(/(\bversionName\s+)"[^"]*"/, `$1"${versionName}"`);
  if (versionCode) out = out.replace(/(\bversionCode\s+)\d+/, `$1${versionCode}`);
  return out;
}

/** ios/App/App.xcodeproj/project.pbxproj: MARKETING_VERSION / CURRENT_PROJECT_VERSION. */
export function patchPbxVersion(pbx, { versionName, versionCode }) {
  let out = pbx.replace(/(\bMARKETING_VERSION = )[^;]+;/g, `$1${versionName};`);
  if (versionCode) out = out.replace(/(\bCURRENT_PROJECT_VERSION = )[^;]+;/g, `$1${versionCode};`);
  return out;
}

function appVersion(env = process.env) {
  const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
  const code = env.DC_BUILD_NUMBER || env.GITHUB_RUN_NUMBER || '';
  return { versionName: String(env.DC_VERSION || pkg.version || '1.0.0'), versionCode: /^\d+$/.test(code) ? code : '' };
}

// ---------------------------------------------------------------------- CLI

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

function patchFile(file, fn) {
  if (!fs.existsSync(file)) throw new Error(`${path.relative(ROOT, file)} not found - run "npx cap add" first`);
  const before = fs.readFileSync(file, 'utf8');
  const after = fn(before);
  if (after !== before) fs.writeFileSync(file, after);
  console.log(`${after === before ? 'unchanged' : 'patched  '} ${path.relative(ROOT, file)}`);
}

function selfTest() {
  const manifest = `<?xml version="1.0" encoding="utf-8"?>
<manifest xmlns:android="http://schemas.android.com/apk/res/android">

    <application
        android:allowBackup="true"
        android:label="@string/app_name"
        android:theme="@style/AppTheme">

        <activity
            android:configChanges="orientation|keyboardHidden|keyboard|screenSize|locale|smallestScreenSize|screenLayout|uiMode"
            android:name=".MainActivity"
            android:launchMode="singleTask"
            android:exported="true">

            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>

        </activity>
    </application>

    <uses-permission android:name="android.permission.INTERNET" />
</manifest>
`;
  const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleDisplayName</key>
	<string>Dungeon Crusade</string>
	<key>UIApplicationSceneManifest</key>
	<dict>
		<key>UISceneConfigurations</key>
		<dict>
			<key>UISupportedInterfaceOrientations</key>
			<array><string>nested, must stay</string></array>
		</dict>
	</dict>
	<key>UIRequiredDeviceCapabilities</key>
	<array>
		<string>armv7</string>
	</array>
	<key>UISupportedInterfaceOrientations</key>
	<array>
		<string>UIInterfaceOrientationPortrait</string>
		<string>UIInterfaceOrientationLandscapeLeft</string>
	</array>
	<key>CFBundleURLTypes</key>
	<array>
		<dict>
			<key>CFBundleURLSchemes</key>
			<array><string>otherapp</string></array>
		</dict>
	</array>
	<key>UIViewControllerBasedStatusBarAppearance</key>
	<true/>
</dict>
</plist>
`;
  const fail = (msg) => {
    throw new Error(`self-test: ${msg}`);
  };
  const a1 = patchAndroidManifest(manifest, { host: 'example.com' });
  const a2 = patchAndroidManifest(a1, { host: 'example.com' });
  if (a1 !== a2) fail('android patch is not idempotent');
  for (const needle of [
    'android:screenOrientation="sensorLandscape"',
    'android:appCategory="game"',
    `android:scheme="${SCHEME}" android:host="join"`,
    'android:scheme="https" android:host="example.com"',
    'android.hardware.gamepad',
    '|navigation|density"',
    'android.intent.category.LAUNCHER',
  ]) {
    if (!a1.includes(needle)) fail(`android output lacks ${needle}`);
  }
  if (a1.split(MARK_BEGIN).length !== 2) fail('android deep links duplicated');
  const a3 = patchAndroidManifest(a1, { host: 'new.example' });
  if (a3.includes('example.com"') || !a3.includes('android:host="new.example"')) fail('android host not replaced');
  if (!/<activity[^>]*sensorLandscape[^>]*>[\s\S]*autoVerify[\s\S]*<\/activity>/.test(a1)) fail('deep links outside activity');

  const p1 = patchInfoPlist(plist);
  const p2 = patchInfoPlist(p1);
  if (p1 !== p2) fail('plist patch is not idempotent');
  const orient = getPlistValue(p1, 'UISupportedInterfaceOrientations');
  if (/Portrait/.test(orient) || !/LandscapeLeft/.test(orient) || !/LandscapeRight/.test(orient)) fail('orientations');
  if (!/Portrait/.test(plist) || !p1.includes('nested, must stay')) fail('nested dict was modified');
  const types = getPlistValue(p1, 'CFBundleURLTypes');
  if (!types.includes('otherapp') || !types.includes(`<string>${SCHEME}</string>`)) fail('URL types not merged');
  for (const k of ['UIRequiresFullScreen', 'GCSupportsControllerUserInteraction', 'GCSupportedGameControllers', 'UISupportedInterfaceOrientations~ipad']) {
    if (getPlistValue(p1, k) == null) fail(`plist lacks ${k}`);
  }
  if (!getPlistValue(p1, 'GCSupportedGameControllers').includes('ExtendedGamepad')) fail('ExtendedGamepad');
  if (!p1.trimEnd().endsWith('</dict>\n</plist>')) fail('plist tail');
  // Well-formedness smoke check: balanced dict/array tags.
  for (const t of ['dict', 'array']) {
    const open = (p1.match(new RegExp(`<${t}>`, 'g')) ?? []).length;
    const close = (p1.match(new RegExp(`</${t}>`, 'g')) ?? []).length;
    if (open !== close) fail(`unbalanced <${t}>`);
  }
  const g = patchGradleVersion('defaultConfig {\n        versionCode 1\n        versionName "1.0"\n}', { versionName: '2.0.0', versionCode: '42' });
  if (!g.includes('versionCode 42') || !g.includes('versionName "2.0.0"')) fail('gradle version');
  const x = patchPbxVersion('CURRENT_PROJECT_VERSION = 1;\nMARKETING_VERSION = 1.0;\nMARKETING_VERSION = 1.0;', { versionName: '2.0.0', versionCode: '' });
  if (x !== 'CURRENT_PROJECT_VERSION = 1;\nMARKETING_VERSION = 2.0.0;\nMARKETING_VERSION = 2.0.0;') fail('pbx version');
  console.log('patch-native self-test: OK');
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const targets = process.argv.slice(2);
  try {
    if (targets.includes('--self-test')) selfTest();
    if (targets.includes('android')) {
      const host = publicHost();
      patchFile(path.join(ROOT, 'android/app/src/main/AndroidManifest.xml'), (s) => patchAndroidManifest(s, { host }));
      patchFile(path.join(ROOT, 'android/app/build.gradle'), (s) => patchGradleVersion(s, appVersion()));
    }
    if (targets.includes('ios')) {
      patchFile(path.join(ROOT, 'ios/App/App/Info.plist'), patchInfoPlist);
      patchFile(path.join(ROOT, 'ios/App/App.xcodeproj/project.pbxproj'), (s) => patchPbxVersion(s, appVersion()));
    }
    if (!targets.length) console.log('usage: patch-native.mjs [android] [ios] [--self-test]');
  } catch (err) {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  }
}
